#!/usr/bin/env python3
"""Generate Exposed artifacts from one indexed palette. --check never writes.
Herdr config is merged by replacing only its theme section, preserving other settings.
"""
import argparse
import json
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[2]
SOURCE = json.loads((ROOT / '.config/exposed/palette.json').read_text())
V = SOURCE['vars']

def hex_color(i):
    assert 16 <= i <= 255
    if i >= 232:
        rgb = [8 + (i - 232) * 10] * 3
    else:
        n, cube = i - 16, [0, 95, 135, 175, 215, 255]
        rgb = [cube[n // 36], cube[n // 6 % 6], cube[n % 6]]
    return '#' + ''.join(f'{v:02x}' for v in rgb)

def color(key):
    return hex_color(V[key])

artifacts = {}
pi = json.loads((ROOT / '.pi/agent/themes/shady.json').read_text())
pi.update(name='exposed', appearance='light', vars=V)
pi['colors']['searchMatchText'] = 'terminalBg'
for n, role in enumerate(['thinkingOff', 'thinkingMinimal', 'thinkingLow', 'thinkingMedium', 'thinkingHigh', 'thinkingXhigh', 'thinkingMax']):
    pi['colors'][role] = f'thinking{n}'
pi['export'] = {'pageBg': 'terminalBg', 'cardBg': 'panel', 'infoBg': 'selection'}
artifacts['.pi/agent/themes/exposed.json'] = json.dumps(pi, indent=2) + '\n'
ansi = ['black', 'red', 'green', 'yellow', 'purple', 'red', 'link', 'normal',
        'comment', 'red', 'green', 'yellow', 'purple', 'red', 'link', 'keyword']
ghostty = ['# Exposed: generated by .config/exposed/generate.py; edit palette.json.',
           f'background = {color("terminalBg")}', f'foreground = {color("normal")}',
           f'cursor-color = {color("normal")}', f'cursor-text = {color("terminalBg")}',
           f'selection-background = {color("selection")}', f'selection-foreground = {color("keyword")}', '']
ghostty += [f'palette = {n}={color(key)}' for n, key in enumerate(ansi)]
artifacts['.config/ghostty/themes/exposed'] = '\n'.join(ghostty) + '\n'
herdr_map = {'accent': 'status', 'panel_bg': 'panel', 'sidebar_bg': 'terminalBg',
             'active_row_bg': 'panel', 'selection_bg': 'selection', 'surface0': 'panel',
             'surface1': 'selection', 'surface_dim': 'separator', 'overlay0': 'comment',
             'overlay1': 'function', 'text': 'normal', 'subtext0': 'comment',
             'mauve': 'identifier', 'green': 'green', 'yellow': 'yellow', 'red': 'attention',
             'blue': 'link', 'teal': 'link', 'peach': 'yellow'}
light = '\n'.join(f'{k} = "{color(v)}"' for k, v in herdr_map.items()) + '\n'
artifacts['.config/herdr/themes/exposed.toml'] = '# Exposed: generated; edit .config/exposed/palette.json.\n' + light
# No unknown theme name: Herdr supports custom light/dark overrides, not custom names.
herdr_path = ROOT / '.config/herdr/config.toml'
existing = herdr_path.read_text()
dark = (ROOT / '.config/herdr/themes/shady.toml').read_text()
assert set(tomllib.loads(dark)) == set(herdr_map)
theme = ('[theme]\n# Built-in names are required by Herdr; every token is overridden.\n'
         'name = "vesper"\nauto_switch = true\ndark_name = "vesper"\nlight_name = "one-light"\n\n'
         '[theme.custom]\n# Safe Shady fallback until host appearance is known.\n' + dark + '\n'
         '[theme.custom.light]\n' + artifacts['.config/herdr/themes/exposed.toml'] + '\n'
         '[theme.custom.dark]\n' + dark + '\n')
# Exactly one contiguous theme region in this config; refuse unsupported layout.
start = existing.index('[theme]')
end = existing.index('[ui]', start)
assert not re.search(r'^\[(?!theme(?:\.|\]))', existing[start:end], re.M)
artifacts['.config/herdr/config.toml'] = existing[:start] + theme + existing[end:]

# Cover every Shady-defined legacy syntax/plugin role with the light palette.
shady = (ROOT / '.vim/pack/minpac/start/shady.vim/colors/shady.vim').read_text()
legacy = {'251': 'normal', '234': 'comment', '236': 'comment', '238': 'status',
          '235': 'selection', '239': 'comment', '245': 'secondary', '172': 'selection',
          '233': 'panel', '52': 'attention', '228': 'yellow', '193': 'number',
          '253': 'keyword', '240': 'comment', '109': 'identifier', '081': 'link',
          '237': 'comment', '255': 'keyword', '244': 'secondary', '246': 'code',
          '232': 'panel', '243': 'secondary', '247': 'function', '242': 'quote',
          '254': 'heading', '252': 'heading', '250': 'heading', '248': 'function',
          'red': 'attention', 'green': 'green', 'yellow': 'yellow', 'cyan': 'link',
          'white': 'normal', 'black': 'black', 'NONE': 'normal'}
groups, links = {}, {}
for line in shady.splitlines():
    m = re.match(r'\s*(?:hi|highlight)\s+(?:link\s+)?([\w@.]+)\s+(.*)', line)
    if not m:
        continue
    name, rest = m.groups()
    if re.match(r'\s*(?:hi|highlight)\s+link\s', line):
        links[name] = rest.split()[0]
        continue
    parts = dict(re.findall(r'(ctermfg|ctermbg|cterm|guisp)=(\S+)', rest))
    if not parts:
        continue
    fg = legacy[parts.get('ctermfg', 'NONE')]
    bg = 'NONE' if parts.get('ctermbg', 'NONE') == 'NONE' else legacy[parts['ctermbg']]
    attr = parts.get('cterm', 'NONE').upper().replace('INVERSE', 'REVERSE')
    groups[name] = (fg, bg, attr)
# Explicit readable UI surfaces and predictable modern Nvim diagnostics/captures.
for names, fg, bg, attr in [
    ('Normal NormalNC NormalFloat', 'normal', 'terminalBg', 'NONE'),
    ('CursorLine CursorColumn ColorColumn', 'normal', 'panel', 'NONE'),
    ('Visual VisualNOS PmenuSel PmenuMatchSel QuickFixLine', 'keyword', 'selection', 'BOLD'),
    ('Pmenu PmenuKind PmenuExtra PmenuShadow PmenuShadowThrough FloatShadow FloatShadowThrough', 'normal', 'panel', 'NONE'),
    ('PmenuSbar', 'status', 'panel', 'NONE'),
    ('PmenuThumb', 'terminalBg', 'status', 'NONE'),
    ('Search IncSearch CurSearch Substitute', 'terminalBg', 'normal', 'NONE'),
    ('StatusLine TabLineSel WinBar', 'keyword', 'selection', 'BOLD'),
    ('StatusLineNC TabLine TabLineFill WinBarNC', 'secondary', 'panel', 'NONE'),
    ('WinSeparator VertSplit FloatBorder MsgSeparator', 'status', 'terminalBg', 'NONE'),
    ('LineNr CursorLineNr SignColumn FoldColumn EndOfBuffer NonText SpecialKey Whitespace', 'comment', 'terminalBg', 'NONE'),
    ('Folded', 'secondary', 'panel', 'NONE'),
    ('DiffAdd diffAdded', 'green', 'panel', 'NONE'),
    ('DiffDelete diffRemoved', 'attention', 'errorPanel', 'NONE'),
    ('DiffChange', 'yellow', 'panel', 'NONE'),
    ('DiffText', 'keyword', 'selection', 'BOLD'),
    ('Error ErrorMsg ErrorSign DiagnosticError', 'attention', 'NONE', 'BOLD'),
    ('Warning WarningMsg DiagnosticWarn', 'yellow', 'NONE', 'BOLD'),
    ('DiagnosticOk Added', 'green', 'NONE', 'NONE'),
    ('Conceal', 'comment', 'NONE', 'NONE'),
    ('RedrawDebugClear RedrawDebugComposed RedrawDebugRecompose', 'keyword', 'selection', 'NONE'),
    ('NvimInternalError NvimFigureBrace NvimSingleQuotedUnknownEscape NvimInvalidSingleQuotedUnknownEscape', 'attention', 'NONE', 'BOLD'),
    ('@markup.heading.1.delimiter.vimdoc @markup.heading.2.delimiter.vimdoc', 'status', 'NONE', 'NONE'),
    ('Changed', 'yellow', 'NONE', 'NONE'),
    ('Removed', 'attention', 'NONE', 'NONE'),
    ('gitCommitOverflow', 'terminalBg', 'attention', 'NONE'),
    ('DiagnosticInfo DiagnosticHint', 'identifier', 'NONE', 'NONE'),
    ('SpellBad SpellCap SpellRare SpellLocal', 'normal', 'NONE', 'UNDERCURL'),
    ('Cursor lCursor TermCursor', 'terminalBg', 'normal', 'NONE'),
    ('MatchParen', 'keyword', 'selection', 'BOLD'),
    ('Todo', 'keyword', 'selection', 'BOLD,ITALIC'),
    ('Directory MoreMsg Question', 'identifier', 'NONE', 'NONE'),
    ('ModeMsg Title', 'keyword', 'NONE', 'BOLD'),
    ('Function Operator', 'function', 'NONE', 'NONE'),
    ('CocErrorHighlight DiagnosticUnderlineError', 'attention', 'NONE', 'UNDERCURL'),
    ('CocWarningHighlight DiagnosticUnderlineWarn', 'yellow', 'NONE', 'UNDERCURL'),
    ('CocInfoHighlight DiagnosticUnderlineInfo', 'identifier', 'NONE', 'UNDERLINE'),
    ('CocHintHighlight DiagnosticUnderlineHint', 'identifier', 'NONE', 'UNDERLINE'),
]:
    for name in names.split():
        groups[name] = (fg, bg, attr)
        links.pop(name, None)
# Theme defaults are deliberately restrained, including variables and comments.
for name, target in {
    '@variable': 'Normal', '@variable.member': 'Identifier', '@variable.parameter': 'Identifier',
    '@constant': 'Constant', '@constant.builtin': 'Constant', '@module': 'Identifier',
    '@string': 'String', '@string.escape': 'Special', '@character': 'String',
    '@number': 'Number', '@boolean': 'Number', '@float': 'Number',
    '@type': 'Type', '@attribute': 'Identifier', '@property': 'Identifier',
    '@function': 'Function', '@function.builtin': 'Function', '@function.call': 'Function',
    '@constructor': 'Type', '@operator': 'Operator', '@keyword': 'Keyword',
    '@punctuation': 'Delimiter', '@comment': 'Comment', '@comment.error': 'Error',
    '@comment.warning': 'Warning', '@comment.todo': 'Todo', '@comment.note': 'Comment',
    '@markup': 'Normal', '@markup.heading': 'markdownH1', '@markup.raw': 'markdownCode',
    '@markup.link': 'markdownLink', '@markup.link.url': 'markdownLink',
    '@markup.list': 'markdownListMarker', '@markup.quote': 'markdownBlockquote',
    '@tag': 'Identifier', '@tag.attribute': 'Identifier', '@tag.delimiter': 'Delimiter',
    'CocErrorFloat': 'Error', 'CocFloating': 'Pmenu', 'CocHintFloat': 'Comment',
    'CocHintSign': 'Comment', 'CocCodeLens': 'Comment', 'CocRustChainingHint': 'Comment',
    'CocInlineVirtualText': 'Comment', 'CocDisabled': 'Comment', 'CocSymbolReference': 'Search',
    'CocSelectedText': 'Visual', 'CocNextEditInsert': 'DiffAdd', 'CocNextEditDelete': 'DiffDelete',
    'CocSearch': 'Link', 'CocMarkdownLink': 'Link', 'CocNotificationProgress': 'Link',
    'mkdBold': 'markdownBold', 'PmenuMatch': 'Keyword',
}.items():
    links[name] = target
    groups.pop(name, None)
for severity in ['Error', 'Warn', 'Info', 'Hint', 'Ok']:
    target = 'DiffAdd' if severity == 'Ok' else f'Diagnostic{severity}'
    for suffix in ['VirtualText', 'VirtualLines', 'Floating', 'Sign']:
        links[f'Diagnostic{suffix}{severity}'] = target
# CoC initializes fixed Gruvbox ANSI groups, including invisible same-color
# foreground/background pairs. Override the installed plugin's complete matrix
# with readable foregrounds on light tints, rather than leaving hidden text.
coc_names = ['Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White', 'Grey']
coc_fg = ['black', 'red', 'green', 'yellow', 'purple', 'red', 'link', 'normal', 'comment']
for foreground, fg in zip(coc_names, coc_fg):
    groups[f'CocListFg{foreground}'] = (fg, 'NONE', 'NONE')
    groups[f'CocListBg{foreground}'] = ('normal', f'ansi{foreground}Bg', 'NONE')
    for background in coc_names:
        groups[f'CocList{foreground}{background}'] = (fg, f'ansi{background}Bg', 'NONE')
groups['CocUnderline'] = ('normal', 'NONE', 'UNDERLINE')
groups['CocLink'] = ('link', 'NONE', 'UNDERLINE')
# Non-colored semantic modifiers inherit the syntax token rather than default rainbow.
for token, target in {'type': 'Type', 'class': 'Type', 'function': 'Function', 'method': 'Function',
                      'variable': 'Normal', 'parameter': 'Identifier', 'property': 'Identifier',
                      'keyword': 'Keyword', 'comment': 'Comment', 'string': 'String', 'number': 'Number'}.items():
    links[f'@lsp.type.{token}'] = target
dark_ansi = [re.search(rf'^palette = {n}=(#[0-9a-f]{{6}})$', (ROOT / '.config/ghostty/themes/shady').read_text(), re.M)[1] for n in range(16)]
wrapper = ['" Native Shady / Exposed pair; generated by .config/exposed/generate.py.',
           "if &background ==# 'light'", '  runtime colors/exposed.vim', 'else',
           "  execute 'source ' . fnameescape(expand('<sfile>:p:h') . '/../pack/minpac/start/shady.vim/colors/shady.vim')",
           '  hi! link CocFloating Pmenu', '  hi! link CocErrorFloat Error',
           '  hi! link CocHintVirtualText Comment', '  hi! link CocHintSign Comment', '  hi! link CocCodeLens Comment']
wrapper += [f"  let g:terminal_color_{n} = '{c}'" for n, c in enumerate(dark_ansi)]
wrapper += ["  let g:terminal_ansi_colors = [" + ', '.join(f"'{c}'" for c in dark_ansi) + ']', 'endif']
artifacts['.vim/colors/shady.vim'] = '\n'.join(wrapper) + '\n'
lines = ['" Exposed: generated by .config/exposed/generate.py; edit palette.json.',
         '" Follow background on native TUI appearance updates (Nvim 0.11+).',
         'if &background ==# "dark"', '  runtime colors/shady.vim', '  finish', 'endif',
         'hi clear', 'if exists("syntax_on")', '  syntax reset', 'endif', 'let g:colors_name = "exposed"', '',
         'let s:palette = {']
lines += [f"      \\ '{key}': [{index}, '{hex_color(index)}']," for key, index in V.items()]
lines += ['      \\ }', '', 'function! s:Hi(group, fg, bg, attrs) abort',
          "  let l:fg = s:palette[a:fg]", "  let l:bg = a:bg ==# 'NONE' ? ['NONE', 'NONE'] : s:palette[a:bg]",
          "  execute 'hi ' . a:group . ' ctermfg=' . l:fg[0] . ' ctermbg=' . l:bg[0] . ' cterm=' . a:attrs",
          "        \\ . ' guifg=' . l:fg[1] . ' guibg=' . l:bg[1] . ' gui=' . a:attrs . ' guisp=' . l:fg[1] . ' blend=0'",
          'endfunction', '']
lines += [f"let g:terminal_color_{n} = '{color(key)}'" for n, key in enumerate(ansi)]
lines += ["let g:terminal_ansi_colors = [" + ', '.join(f"'{color(key)}'" for key in ansi) + ']', '']
lines += [f"call s:Hi('{name}', '{fg}', '{bg}', '{attrs}')" for name, (fg, bg, attrs) in sorted(groups.items())]
lines += ['', '" Language, Markdown, CoC, Tree-sitter and semantic aliases.']
lines += [f'hi! link {name} {target}' for name, target in sorted(links.items())]
artifacts['.vim/colors/exposed.vim'] = '\n'.join(lines) + '\n'

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, content in artifacts.items():
    destination = ROOT / path
    if args.check:
        assert destination.exists() and destination.read_text() == content, f'Stale artifact: {path}'
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content)
print(('PASS' if args.check else 'Generated') + f' {len(artifacts)} coherent Exposed artifacts')
